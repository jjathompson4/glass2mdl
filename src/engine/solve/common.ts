/**
 * MDL's custom_curve_layer takes a scalar reflectivity, so a colored
 * reflectance is split into a level and a hue: the brightest channel becomes
 * normal_reflectivity and the color is normalized against it, so their product
 * reproduces the fitted RGB reflectance exactly.
 *
 * Both places this is used put a transmission-only BSDF underneath, so the
 * layer owns all of the reflection and the fitted value comes through intact.
 */
export type CoatingLayerIR = Extract<LayerIR, { kind: "fresnel-coating" }>;

export function coatingLayer(reflectance: RGB): CoatingLayerIR {
  const peak = maxChannel(reflectance);
  const color = peak > 1e-6 ? scaleRGB(reflectance, 1 / peak) : { r: 1, g: 1, b: 1 };

  return {
    kind: "fresnel-coating",
    normalReflectivity: Math.min(1, Math.max(0, peak)),
    grazingReflectivity: 1,
    reflectColor: color,
  };
}

/**
 * Pre-divide a transmission tint by the light the layer above it keeps.
 *
 * Same mixing rule seen from the other side: a coating layered at weight w
 * passes only `(1-w)` of the base through, so the base tint must be raised to
 * land on the measured transmittance. Returns the compensated tint plus
 * whether it had to be clamped, since a clamp means the target is out of reach.
 */
export function compensateForLayer(
  tint: RGB,
  layerWeight: number,
): { tint: RGB; clamped: boolean } {
  const passthrough = Math.max(1e-6, 1 - layerWeight);
  const raised = scaleRGB(tint, 1 / passthrough);
  const peak = maxChannel(raised);
  if (peak <= 1) return { tint: raised, clamped: false };
  return { tint: scaleRGB(raised, 1 / peak), clamped: true };
}

/** Beer-Lambert absorption per meter, per channel. */
export function volumeAbsorption(internalT: RGB, thicknessMm: number): RGB {
  const d = thicknessMm / 1000;
  return {
    r: absorptionCoefficient(internalT.r, d),
    g: absorptionCoefficient(internalT.g, d),
    b: absorptionCoefficient(internalT.b, d),
  };
}

const pct = (v: number) => `${(v * 100).toFixed(1)}%`;

/**
 * Header written above every generated material: what was asked for, what came
 * out, and which approximations are baked in. A generated file should be
 * enough on its own to reconstruct or question the result.
 */
export function provenanceComments(
  input: GlazingSystemInput,
  mode: ExportMode,
  fit: AssemblyFit,
  extraNotes: string[] = [],
): string[] {
  const residual = fitResidual(fit, input);
  const lines = [
    `Generated by ${TOOL_NAME} ${TOOL_VERSION} - ${mode} export`,
    `System: ${input.name}`,
    "",
    "Data sheet input:",
    `  Visible transmittance (VLT): ${pct(input.assembly.tvis)}`,
    `  Visible reflectance, exterior: ${pct(input.assembly.rvisExt)}`,
    `  Visible reflectance, interior: ${pct(input.assembly.rvisInt)}`,
  ];

  input.lites.forEach((lite, i) => {
    const coating = lite.coating
      ? `, ${lite.coating.kind} coating on surface #${lite.coating.surface}`
      : "";
    lines.push(`  Lite ${i + 1}: ${lite.thickness}mm ${SUBSTRATE_LABELS[lite.substrate]}${coating}`);
    const gap = input.gaps[i];
    if (gap) lines.push(`  Gap ${i + 1}: ${gap.width}mm`);
  });

  if (input.frit) {
    lines.push(
      `  Frit: ${input.frit.pattern.kind} on surface #${input.frit.surface}, opacity ${pct(input.frit.opacity)}`,
    );
  }

  lines.push(
    "",
    "Fitted result:",
    `  Transmittance: ${pct(luminance(fit.achieved.t))} (residual ${(residual.tvis * 100).toFixed(2)} pts)`,
    `  Reflectance ext: ${pct(luminance(fit.achieved.rFront))} (residual ${(residual.rvisExt * 100).toFixed(2)} pts)`,
    `  Reflectance int: ${pct(luminance(fit.achieved.rBack))} (residual ${(residual.rvisInt * 100).toFixed(2)} pts)`,
  );

  if (extraNotes.length) lines.push("", "Notes:", ...extraNotes.map((n) => `  - ${n}`));
  return lines;
}

/** Per-lite numbers for the UI breakdown panel and the preview shader. */
export function buildDerived(input: GlazingSystemInput, fit: AssemblyFit): DerivedOptics {
  return {
    lites: input.lites.map((lite, i) => {
      const internalT = fit.internalT[i];
      const isCoated = fit.coating?.location.lite === i;
      return {
        index: i,
        thickness: lite.thickness,
        internalTransmittance: internalT,
        absorptionCoefficient: volumeAbsorption(internalT, lite.thickness),
        ...(isCoated && fit.coating
          ? {
              coatingR0: maxChannel(fit.coating.rExt),
              coatingColor: lite.coating?.reflectedColor ?? fit.coating.rExt,
            }
          : {}),
      };
    }),
    coating: fit.coating
      ? {
          surface: input.lites.find((l) => l.coating)?.coating?.surface ?? 0,
          transmission: fit.coating.tau,
          reflectanceExt: fit.coating.rExt,
          reflectanceInt: fit.coating.rInt,
        }
      : undefined,
    recomputed: { t: fit.achieved.t, rFront: fit.achieved.rFront, rBack: fit.achieved.rBack },
    residual: fitResidual(fit, input),
  };
}
